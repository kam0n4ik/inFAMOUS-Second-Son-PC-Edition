"""Generates engine/resources/type_registry_table.inc - research tool, run by hand.

The packages name the type of every object by a 64-bit type-name hash in their DIC fixups (the hash is
not derivable from the name: it is looked up in the eboot dictionary 0xa5ff70, whose value is the index
into the class-name array 0xdac130). The native runtime cannot read the eboot, so the few hundred types
that actually occur in the packages it loads are listed here once.

Only hashes seen at object headers (+0x10 of root-catalog objects) and as class hashes of PLPS records
in the scanned packages are emitted.
usage: py -I -X utf8 gen_type_table.py <out.inc>
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.join(HERE, '..'), os.path.join(HERE, '..', 'anim')]
import kcap  # noqa: E402
import objects as O  # noqa: E402
from pkg import Pkg  # noqa: E402

CACHE = 'E:/shdps4/CUSA00004/art/cache/'


def wanted(name):
    if not name.endswith('.xpps') or name.endswith('.hires.xpps') or '#tandem#' in name:
        return False
    return (name.startswith(('msn_', 'graffiti_', 'lang_english_text', 'world_village', 'i3.sprig'))
            or (name[0] == 'a' and name[1:2].isdigit()))


def main():
    names, tab = O.type_names()
    import ebootimg
    enums = ebootimg.enums()  # "cid_<CLASS>" entries: computable with NameHash, not listed
    tab = {h: v for h, v in tab.items() if h not in enums}
    seen = {}
    files = sorted(f for f in os.listdir(CACHE) if wanted(f))
    for f in files:
        p = Pkg(f[:-5])
        dic = dict(p.dic)
        for o in O.catalog(p):
            h = dic.get(o['addr'] + 0x10)
            if h is not None and h in tab and tab[h] < len(names) and names[tab[h]]:
                seen[h] = (tab[h], names[tab[h]])
        for b in p.bl:
            if b['type'] != 2:
                continue
            st = p.hs + b['offset']
            for tag, pl, size in kcap.chunks(p.d, st, st + b['size']):
                if tag != kcap.TAG_PLPS:
                    continue
                n1, n2 = struct.unpack_from('<II', p.d, pl)
                n3 = struct.unpack_from('<I', p.d, pl + 8)[0]
                o = pl + 0x10
                hashes = [struct.unpack_from('<Q', p.d, o + i * 0x18 + 8)[0] for i in range(n1)]
                o += n1 * 0x18
                hashes += [struct.unpack_from('<Q', p.d, o + i * 0x30 + 8)[0] for i in range(n2)]
                for h in hashes:
                    if h in tab and tab[h] < len(names) and names[tab[h]]:
                        seen[h] = (tab[h], names[tab[h]])
    lines = ['// Generated by native/tools/research/missions/gen_type_table.py from %d packages - do not edit.' % len(files),
             '// {type-name hash as stored in DIC/PLPS records, class-table index, name}']
    for h in sorted(seen):
        idx, name = seen[h]
        lines.append('{0x%016xull, %d, "%s"},' % (h, idx, name))
    with open(sys.argv[1], 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('types', len(seen), 'from', len(files), 'packages')


if __name__ == '__main__':
    main()
